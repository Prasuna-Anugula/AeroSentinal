"""
AeroSentinel — Report Service
Generates CSV and PDF engine health reports.
"""
from __future__ import annotations
import csv
import io
import logging
from datetime import datetime
from typing import Dict

logger = logging.getLogger(__name__)


def generate_csv_report(data: Dict) -> bytes:
    """Generate a CSV bytes report for a single engine prediction."""
    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow(["AeroSentinel Engine Health Report"])
    writer.writerow(["Generated", datetime.utcnow().isoformat()])
    writer.writerow([])

    writer.writerow(["ENGINE INFORMATION"])
    writer.writerow(["Engine Unit",       data.get("engine_unit")])
    writer.writerow(["Dataset",           data.get("dataset")])
    writer.writerow(["Last Cycle",        data.get("last_cycle")])
    writer.writerow(["Health Status",     data.get("health_status")])
    writer.writerow([])

    writer.writerow(["RUL PREDICTION"])
    writer.writerow(["Predicted RUL (cycles)", data.get("predicted_rul")])
    writer.writerow(["True RUL (if available)", data.get("true_rul")])
    writer.writerow(["RUL Model",             data.get("rul_model")])
    writer.writerow([])

    writer.writerow(["FAILURE RISK"])
    writer.writerow(["Failure Probability",   data.get("failure_probability")])
    writer.writerow(["Risk Level",            data.get("risk_level")])
    writer.writerow(["Classifier Model",      data.get("fail_model")])
    writer.writerow([])

    writer.writerow(["ANOMALY DETECTION"])
    writer.writerow(["Overall Anomaly Score", data.get("anomaly_score")])
    writer.writerow(["Anomaly Severity",      data.get("anomaly_severity")])
    writer.writerow([])

    writer.writerow(["MAINTENANCE RECOMMENDATION"])
    writer.writerow(["Priority",        data.get("priority")])
    writer.writerow(["Recommendation",  data.get("recommendation")])
    writer.writerow([])

    writer.writerow(["DISCLAIMER"])
    writer.writerow([
        "Predictions are generated by the AeroSentinel ML pipeline using the "
        "NASA C-MAPSS dataset. These are research-grade estimates, not certified "
        "aviation maintenance recommendations."
    ])

    return output.getvalue().encode("utf-8")


def generate_pdf_report(data: Dict) -> bytes:
    """Generate a PDF report. Uses reportlab if available, falls back to plain text."""
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.lib.styles   import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units    import inch
        from reportlab.lib           import colors
        from reportlab.platypus      import (SimpleDocTemplate, Paragraph,
                                             Spacer, Table, TableStyle)

        buffer = io.BytesIO()
        doc    = SimpleDocTemplate(buffer, pagesize=letter,
                                   leftMargin=inch, rightMargin=inch,
                                   topMargin=inch, bottomMargin=inch)
        styles = getSampleStyleSheet()
        story  = []

        title_style = ParagraphStyle("title", parent=styles["Title"],
                                     fontSize=18, textColor=colors.HexColor("#1a3a6b"))
        h2_style    = ParagraphStyle("h2",    parent=styles["Heading2"],
                                     fontSize=12, textColor=colors.HexColor("#1a3a6b"))

        story.append(Paragraph("AeroSentinel Engine Health Report", title_style))
        story.append(Paragraph(f"Generated: {datetime.utcnow().isoformat()}", styles["Normal"]))
        story.append(Spacer(1, 0.2 * inch))

        def section(title, rows):
            story.append(Paragraph(title, h2_style))
            t = Table(rows, colWidths=[2.5 * inch, 3.5 * inch])
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e8edf5")),
                ("GRID",       (0, 0), (-1, -1), 0.5, colors.grey),
                ("FONTSIZE",   (0, 0), (-1, -1), 10),
                ("PADDING",    (0, 0), (-1, -1), 5),
            ]))
            story.append(t)
            story.append(Spacer(1, 0.15 * inch))

        section("Engine Information", [
            ["Engine Unit",   str(data.get("engine_unit", ""))],
            ["Dataset",       str(data.get("dataset", ""))],
            ["Last Cycle",    str(data.get("last_cycle", ""))],
            ["Health Status", str(data.get("health_status", "")).upper()],
        ])

        section("RUL Prediction", [
            ["Predicted RUL (cycles)", str(data.get("predicted_rul", ""))],
            ["True RUL",               str(data.get("true_rul", "N/A"))],
            ["Model",                  str(data.get("rul_model", ""))],
        ])

        section("Failure Risk", [
            ["Failure Probability", str(data.get("failure_probability", ""))],
            ["Risk Level",         str(data.get("risk_level", "")).upper()],
            ["Classifier",        str(data.get("fail_model", ""))],
        ])

        section("Anomaly Detection", [
            ["Anomaly Score",    str(data.get("anomaly_score", ""))],
            ["Severity",         str(data.get("anomaly_severity", ""))],
        ])

        section("Maintenance Recommendation", [
            ["Priority",        str(data.get("priority", "")).upper()],
            ["Recommendation",  str(data.get("recommendation", ""))],
        ])

        story.append(Paragraph(
            "DISCLAIMER: Predictions are generated by the AeroSentinel ML pipeline "
            "using the NASA C-MAPSS dataset. These are research-grade estimates, "
            "not certified aviation maintenance recommendations.",
            styles["Italic"],
        ))

        doc.build(story)
        return buffer.getvalue()

    except ImportError:
        # Fallback: return CSV as bytes if reportlab not installed
        logger.warning("reportlab not installed — falling back to CSV for PDF report.")
        return generate_csv_report(data)
